val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use(::load)
}

fun configuredValue(name: String): String? =
    providers.gradleProperty(name).orNull
        ?: System.getenv(name)
        ?: localProperties.getProperty(name)

val releaseStorePath = configuredValue("QRAFT_KEYSTORE_PATH")
val releaseStorePassword = configuredValue("QRAFT_KEYSTORE_PASSWORD")
val releaseKeyAlias = configuredValue("QRAFT_KEY_ALIAS")
val releaseKeyPassword = configuredValue("QRAFT_KEY_PASSWORD")

val hasReleaseSigning = !releaseStorePath.isNullOrBlank() &&
    !releaseStorePassword.isNullOrBlank() &&
    !releaseKeyAlias.isNullOrBlank() &&
    !releaseKeyPassword.isNullOrBlank()

